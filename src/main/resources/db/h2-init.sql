CREATE TABLE IF NOT EXISTS pessoas (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL
    );

CREATE TABLE IF NOT EXISTS usuarios (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    senha VARCHAR(60) NOT NULL,
    ativo BOOLEAN NOT NULL
    );

CREATE TABLE IF NOT EXISTS tipos_conta (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           nome VARCHAR(60) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS contas_bancarias (
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                agencia VARCHAR(4) NOT NULL,
    numero VARCHAR(8) NOT NULL,
    saldo DECIMAL(19, 2) NOT NULL DEFAULT 0,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    titular_id BIGINT NOT NULL,
    tipo_conta_id BIGINT NOT NULL,

    CONSTRAINT fk_conta_titular
    FOREIGN KEY (titular_id)
    REFERENCES pessoas(id),

    CONSTRAINT fk_conta_tipo
    FOREIGN KEY (tipo_conta_id)
    REFERENCES tipos_conta(id),

    CONSTRAINT uk_conta_agencia_numero
    UNIQUE (agencia, numero)
    );
